const DICTS: Record<Lang, Dict> = { es, en, fr, de, it };

let current: Lang = 'es';

export function isLang(value: string): value is Lang {
  return (LANGS as readonly string[]).includes(value);
}

/** Saved choice first, then the browser language, then Spanish. */
export function initialLang(): Lang {
  const saved = localStorage.getItem('mai-reel-lang');
  if (saved && isLang(saved)) return saved;
  const nav = (navigator.language || 'es').slice(0, 2).toLowerCase();
  return isLang(nav) ? nav : 'es';
}

export function setLang(l: Lang): void {
  current = l;
  localStorage.setItem('mai-reel-lang', l);
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return current;
}

export function t(key: string): string {
  return DICTS[current][key] ?? DICTS.en[key] ?? DICTS.es[key] ?? key;
}

/** `t` with `{placeholder}` interpolation. */
export function tf(key: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce(
    (acc, [name, value]) => acc.split(`{${name}}`).join(String(value)),
    t(key),
  );
}
